-- Core banking DB2 schema

CREATE TABLE CUSTOMER_MASTER (
    CUSTOMER_ID        CHAR(10)       NOT NULL PRIMARY KEY,
    CUSTOMER_NAME      VARCHAR(60)    NOT NULL,
    CUSTOMER_ADDRESS   VARCHAR(80),
    CUSTOMER_STATUS    CHAR(1)        NOT NULL,
    OPENED_DATE        DATE,
    LAST_STATEMENT_DATE DATE
);

CREATE TABLE ACCOUNT_MASTER (
    ACCOUNT_ID         CHAR(12)       NOT NULL PRIMARY KEY,
    CUSTOMER_ID        CHAR(10)       NOT NULL REFERENCES CUSTOMER_MASTER (CUSTOMER_ID),
    CURRENT_BALANCE    DECIMAL(11,2)  NOT NULL,
    INTEREST_RATE      DECIMAL(7,4)   NOT NULL,
    ACCOUNT_STATUS     CHAR(1)        NOT NULL,
    LAST_ACTIVITY_DATE DATE
);

CREATE TABLE PAYMENT_LEDGER (
    PAYMENT_ID         CHAR(16)       NOT NULL PRIMARY KEY,
    ACCOUNT_ID         CHAR(12)       NOT NULL REFERENCES ACCOUNT_MASTER (ACCOUNT_ID),
    AMOUNT             DECIMAL(11,2)  NOT NULL,
    MAIL_ADDRESS       VARCHAR(80),
    POSTED_DATE        DATE           NOT NULL
);

CREATE TABLE BRANCH_LEGACY (
    BRANCH_CODE        CHAR(6)        NOT NULL PRIMARY KEY,
    BRANCH_NAME        VARCHAR(40),
    TELEX_NUMBER       VARCHAR(20)
);

CREATE TABLE AUDIT_ARCHIVE (
    AUDIT_ID           CHAR(20)       NOT NULL PRIMARY KEY,
    ARCHIVED_ON        DATE,
    PAYLOAD            VARCHAR(2000)
);
